const matchExtension = (lowerName: string): IconConfig | undefined => {
  // 从第一个点开始尝试，复合扩展名优先；点文件（.gitignore）按点后部分匹配
  let idx = lowerName.indexOf(".");
  while (idx !== -1) {
    const config = EXTENSION_MAP[lowerName.slice(idx + 1)];
    if (config) {
      return config;
    }
    idx = lowerName.indexOf(".", idx + 1);
  }
  return undefined;
};

export const getIconConfig = (
  name: string,
  isDirectory: boolean = false,
  isExpanded: boolean = false,
): IconConfig => {
  if (isDirectory) {
    return li(isExpanded ? FolderOpen : Folder, "#dcb67a");
  }

  // 兼容传入完整路径
  const baseName = name.split(/[\\/]/).pop() || name;
  const lowerName = baseName.toLowerCase();
  if (!lowerName.includes(".")) {
    return NO_EXT_MAP[lowerName] ?? li(File, "#6c757d");
  }
  return matchExtension(lowerName) ?? li(File, "#6c757d");
};

export const getFileTypeIcon = (
  name: string,
  isDirectory: boolean = false,
  isExpanded: boolean = false,
  props?: LucideProps,
): React.JSX.Element => {
  const { component: IconComponent, color } = getIconConfig(
    name,
    isDirectory,
    isExpanded,
  );

  const style: React.CSSProperties = { ...props?.style };
  if (color) {
    style.color = color;
  }

  const { size, className, style: _style, ...rest } = props ?? {};

  return (
    <IconComponent size={size} className={className} style={style} {...rest} />
  );
};

