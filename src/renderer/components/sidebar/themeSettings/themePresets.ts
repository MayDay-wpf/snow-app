const LEGACY_PRESET_ID_ALIASES: Record<string, string> = {
  "snow-light": "snow",
  "snow-dark": "snow",
  "solarized-light": "solarized",
  "solarized-dark": "solarized",
  // anthropic 预设已更名为 cream，映射旧 id 以兼容已持久化的选择。
  "anthropic": "cream",
};

export const resolvePresetId = (id: string): string =>
  LEGACY_PRESET_ID_ALIASES[id] ?? id;

export const getPresetById = (id: string): ThemePreset | undefined =>
  THEME_PRESETS.find((preset) => preset.id === resolvePresetId(id));
